// A copy of the web portal's src/lib/api/types.ts, the API contract; keep the two in step.

export type PropertyStatus = "for-sale" | "for-rent" | "sold" | "pending";

export type PropertyType =
    | "house"
    | "apartment"
    | "condo"
    | "villa"
    | "townhouse"
    | "land"
    | "farm-lot"
    | "commercial"
    | "industrial";

export interface Address {
    line1: string;
    /**
     * Neighborhood or district within the city, e.g. "Pacific Heights", which drives the
     * programmatic-SEO area pages (`/[category]/[city]/[area]`).
     */
    neighborhood: string;
    city: string;
    /**
     * URL segments owned by the API rather than derived from the names above, so a city can
     * display as "Island Garden City of Samal" while living at `/houses-for-sale/samal`;
     * optional, with `citySlugOf` / `areaSlugOf` in `@/lib/seo/taxonomy` slugifying the
     * display name when one is missing.
     */
    citySlug?: string;
    areaSlug?: string;
    state: string;
    zip: string;
    country: string;
}

export interface GeoPoint {
    lat: number;
    lng: number;
}

export interface Property {
    id: string;
    slug: string;
    title: string;
    /**
     * Plain text, because the meta description, the JSON-LD and the listing cards all need
     * markup-free prose, with paragraphs separated by a blank line.
     */
    description: string;
    /**
     * The same description as sanitised markup from the admin's rich editor, optional
     * because anything written before that editor existed has only the plain text above,
     * which the listing page falls back to.
     */
    descriptionHtml?: string;
    status: PropertyStatus;
    type: PropertyType;
    /** Price in the smallest sensible whole unit of `currency` (e.g. dollars). */
    price: number;
    currency: string;
    /** Monthly price for rentals; null for sales. */
    rentPeriod?: "month" | "week" | null;
    bedrooms: number;
    bathrooms: number;
    /** Living area in square metres. */
    area: number;
    /** Lot size in square metres, when applicable. */
    lotSize?: number;
    yearBuilt?: number;
    address: Address;
    location: GeoPoint;
    /**
     * Where the listing may be shown when `location` is empty, being the centre of its
     * neighborhood or city and never a guess at the address, which is why `getPropertyPins`
     * collects everything sharing a centre into one labelled group.
     */
    approximateLocation?: GeoPoint | null;
    images: string[];
    /**
     * Tiny inlined preview of `images[0]` shown blurred while the real photo downloads,
     * generated by the API on upload because the portal cannot derive it from an image URL.
     */
    blurDataUrl?: string;
    /** Video URLs for the listing; optional until the API provides them. */
    videos?: string[];
    features: string[];
    featured: boolean;
    agentId: string;
    createdAt: string;
}

export type PrcRole = "broker" | "salesperson";

export interface RealtyRef {
    name: string;
    slug: string;
}

/** An active realty (others 404), whose counts are of exactly what its page shows. */
export interface Realty extends RealtyRef {
    id: string;
    logo: string | null;
    about: string;
    address: string;
    city: RealtyRef | null;
    email: string;
    phone: string;
    /** A Facebook page username → m.me/<username>; absent when the realty gave none. */
    messenger?: string | null;
    /** Confirmed, PRC-verified agents with a public profile. */
    agentsCount: number;
    /** Active listings by those agents. */
    listingsCount: number;
    /** Present on the realty's own page only, and null unless they are one of its `agents`. */
    principalBroker?: RealtyRef | null;
    /** Present on the realty's own page only. */
    agents?: Agent[];
}

export type RealtySort = "name" | "agents" | "listings";

export interface RealtyQuery {
    page?: number;
    pageSize?: number;
    /** Matched against the realty's name. */
    search?: string;
    /** A city slug, e.g. `davao-city`. */
    city?: string;
    sort?: RealtySort;
}

export interface Agent {
    id: string;
    slug: string;
    name: string;
    title: string;
    bio: string;
    email: string;
    phone: string;
    avatar: string;
    /** Always true, because the backend only serves agents whose PRC ID it has verified. */
    verified: boolean;
    /** Decides the badge: a broker is licensed, a salesperson is accredited and never "licensed". */
    prcRole: PrcRole;
    /** Only a realty that confirmed this agent; null is not "independent" and must not be shown as such. */
    realty: RealtyRef | null;
    listingsCount: number;
    yearsExperience: number;
    specialties: string[];
    languages: string[];
    /**
     * Chat channels the agent manages in Filament, any of which may be absent, holding raw
     * handles the portal turns into deep links (see `@/lib/contact`).
     */
    messenger?: string; // Facebook page username → m.me/<username>
    whatsapp?: string; // E.164 digits, no "+", e.g. "639171234567" → wa.me/<digits>
    viber?: string; // E.164 with "+", e.g. "+639171234567" → viber://chat
    social: {
        twitter?: string;
        linkedin?: string;
        facebook?: string;
        instagram?: string;
    };
}

/**
 * Which contact channel a buyer tapped, kept as a value so the server actions can check an
 * untrusted `source` against it at runtime.
 */
export const LEAD_SOURCES = [
    "messenger",
    "viber",
    "whatsapp",
    "call",
    "sms",
    "viewing-request",
    "form",
] as const;

export type LeadSource = (typeof LEAD_SOURCES)[number];

/**
 * A contact attempt, written before the hand-off so every intent is captured, born
 * `initiated` and advanced by the agent in the backend.
 */
export interface LeadPayload {
    source: LeadSource;
    propertyId?: string;
    agentId?: string;
    /**
     * The code this visit put into the prefilled chat message, e.g. `GT-4K7P2Q`, minted
     * here because the hand-off must not wait on a round trip, with the API validating the
     * shape and minting its own when none is sent.
     */
    reference?: string;
}

export interface LeadResult {
    ok: boolean;
    id?: string;
}

export interface Paginated<T> {
    items: T[];
    total: number;
    page: number;
    pageSize: number;
    totalPages: number;
}

export interface PropertyQuery {
    page?: number;
    pageSize?: number;
    status?: PropertyStatus;
    type?: PropertyType;
    city?: string;
    /** Exact neighborhood match (case-insensitive). */
    neighborhood?: string;
    minPrice?: number;
    maxPrice?: number;
    minBeds?: number;
    /** Square metres, like `Property.lotSize`. */
    minLotSize?: number;
    /**
     * Free-text search across the listing's title, description and street address and the
     * names of its city and area, the area included because "Matina" or "Buhangin" is what
     * buyers here type first and it is a separate relation on the backend.
     */
    q?: string;
    featured?: boolean;
    agentId?: string;
    /** A realty slug: the listings of the agents its page shows. */
    realty?: string;
    sort?: "newest" | "price-asc" | "price-desc";
}

export interface ContactPayload {
    name: string;
    email: string;
    phone?: string;
    message: string;
    /** Optional context: the property or agent the enquiry relates to. */
    propertyId?: string;
    agentId?: string;
}

export interface ContactResult {
    ok: boolean;
    id?: string;
    message: string;
}
